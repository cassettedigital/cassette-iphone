// The Android app (a fork of Tempo, its own git under apps/cassette-player-android) compiles the Kotlin
// from inside its own tree, so it gets a copy too when that checkout is here. Commit it in that repo.
const ANDROID = path.join(here, "..", "..", "apps", "cassette-player-android", "app", "src", "main", "java");
const androided = fs.existsSync(ANDROID);
if (androided) {
  fs.mkdirSync(path.join(ANDROID, "digital", "cassette", "kit"), { recursive: true });
  fs.writeFileSync(path.join(ANDROID, "digital", "cassette", "kit", "CassetteKitTokens.kt"), kt.join("\n"));
  // Android's own resource files, so the app's colours, sizes and type read the kit directly: change a
  // value in tokens.json, run generate, and Android moves with the iPhone and the web. Colours come in
  // two files (values/ is the light paper, values-night/ the dark one) so the app follows the phone.
  const RES = path.join(ANDROID, "..", "res");
  const snake = (k) => k.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
  const num = (v) => String(Math.round(v * 1000) / 1000);
  const xml = (lines) => ['<?xml version="1.0" encoding="utf-8"?>', `<!-- ${HEAD} -->`, "<resources>", ...lines, "</resources>", ""].join("\n");
  const light = [];
  const dark = [];
  for (const [k, v] of Object.entries(t.color)) {
    light.push(`    <color name="kit_${snake(k)}">${lightHex(v).toUpperCase()}</color>`);
    dark.push(`    <color name="kit_${snake(k)}">${v.hex.toUpperCase()}</color>`);
  }
  for (const [k, v] of Object.entries(t.radius)) light.push(`    <dimen name="kit_radius_${snake(k)}">${num(v)}dp</dimen>`);
  for (const [k, v] of Object.entries(t.space)) light.push(`    <dimen name="kit_space_${snake(k)}">${num(v)}dp</dimen>`);
  for (const [k, v] of Object.entries(t.opacity)) light.push(`    <item name="kit_opacity_${snake(k)}" format="float" type="dimen">${num(v)}</item>`);
  for (const [comp, spec] of Object.entries(t.component)) {
    for (const [k, v] of Object.entries(spec)) {
      if (typeof v !== "number") continue;
      // alphas and fractions are plain numbers; everything else is a length
      const plain = v > 0 && v < 1 && /alpha|ring|fade|from/i.test(k);
      light.push(plain
        ? `    <item name="kit_${snake(comp)}_${snake(k)}" format="float" type="dimen">${num(v)}</item>`
        : `    <dimen name="kit_${snake(comp)}_${snake(k)}">${num(v)}dp</dimen>`);
    }
  }
  for (const [k, v] of Object.entries(t.type)) {
    light.push(`    <dimen name="kit_type_${snake(k)}">${num(v.size)}sp</dimen>`);
    light.push(`    <integer name="kit_type_${snake(k)}_weight">${v.weight}</integer>`);
    // the kit's kern is in points; Android's letterSpacing is in ems
    light.push(`    <item name="kit_type_${snake(k)}_tracking" format="float" type="dimen">${num((v.kern ?? 0) / v.size)}</item>`);
  }
  for (const [k, v] of Object.entries(t.shape)) light.push(`    <item name="kit_shape_${snake(k)}" format="float" type="dimen">${num(v)}</item>`);
  fs.mkdirSync(path.join(RES, "values"), { recursive: true });
  fs.mkdirSync(path.join(RES, "values-night"), { recursive: true });
  fs.writeFileSync(path.join(RES, "values", "cassette_kit.xml"), xml(light));
  fs.writeFileSync(path.join(RES, "values-night", "cassette_kit.xml"), xml(dark));
}
